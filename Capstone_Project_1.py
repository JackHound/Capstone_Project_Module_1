def cari_buku():
    while True:
        print('''
        ============ SEARCH BOOK ============

        1. Cari berdasarkan judul
        2. Cari berdasarkan author
        3. Cari berdasarkan publisher
        4. Filter berdasarkan tahun
        5. Sort judul A-Z
        6. Sort judul Z-A
        7. Sort tahun terbit ascending
        8. Sort tahun terbit descending
        9. Kembali
        ''')
        choice  = input("Masukkan pilihan anda (1-9):")
        hasil_pencarian = {}
        if choice == "1":
            title = input("Masukkan judul buku yang ingin dicari:")
            for kode, buku in books_db.items():
                if title.lower() in buku["book_title"].lower():
                    hasil_pencarian[kode] = buku
            book_list(hasil_pencarian)
        elif choice == "2":
            author = input("Masukkan nama author yang ingin dicari:")
            for kode, buku in books_db.items():
                if author.lower() in buku["book_author"].lower():
                    hasil_pencarian[kode] = buku
            book_list(hasil_pencarian)
        elif choice == "3":
            publisher = input("Masukkan nama publisher yang ingin dicari:")
            for kode, buku in books_db.items():
                if publisher.lower() in buku["book_publisher"].lower():
                    hasil_pencarian[kode] = buku
            book_list(hasil_pencarian)
        elif choice == "4":
            year = int(input("Masukkan tahun terbit yang ingin dicari:"))
            for kode, buku in books_db.items():
                if year == buku["year_of_book_publication"]:
                    hasil_pencarian[kode] = buku
            book_list(hasil_pencarian)
        elif choice == "5":
            sorted_books = dict(sorted(books_db.items(), key = lambda x: x[1]['book_title'].lower()))
            book_list(sorted_books)
        elif choice == "6":
            sorted_books = dict(sorted(books_db.items(), key = lambda x: x[1]['book_title'].lower(), reverse=True))
            book_list(sorted_books)
        elif choice == "7":
            sorted_books = dict(sorted(books_db.items(), key = lambda x: x[1]['year_of_book_publication']))
            book_list(sorted_books)
        elif choice == "8":
            sorted_books = dict(sorted(books_db.items(), key = lambda x: x[1]['year_of_book_publication'], reverse=True))
            book_list(sorted_books)
        elif choice == "9":
            break
        else:
            print("Masukkan pilihan yang valid!")

