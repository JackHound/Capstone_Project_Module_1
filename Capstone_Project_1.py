def id_gen(index,books_db, recycle_bin):
    all_ids = []
    all_ids.extend(books_db.keys())
    all_ids.extend(recycle_bin.keys())

    if not all_ids:
        return f"{index}000001"

    max_id = max(
    int(id_[1:])
    for id_ in all_ids
    if id_.startswith(index))

    return f"{index}{max_id + 1:06d}"

